using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using UnityEngine;
using WildWasteland.Core;
using WildWasteland.Modules.Presentation;
namespace WildWasteland.Modules.PlayerBody
{
    /// <summary>Presentation-owned live pose context and storage; Tools supplies input through an owned callback.</summary>
    internal static partial class GunPose
    {
        private static int _sel = -1;
        internal static int EditorTarget;
        internal static string CurrentWeapon = "", CurrentPose = "";
        internal static float[] CurrentShown;
        internal static int CurrentFrame = -1;
        internal static string AimLine = "", _note = "", _status = "";
        /// <summary>Editor activation belongs to the current registered editor owner.</summary>
        public static bool Editing { get { return PoseEditorApi.Active && PoseEditorApi.Enabled; } }
        /// <summary>Selected runtime preview clip, enabled only in third person.</summary>
        public static string Preview { get { return Editing && ThirdPerson.On && _sel >= 0 && _sel < _list.Count ? _list[_sel] : null; } }
        /// <summary>Returns to the character's currently playing clip.</summary>
        public static void ResetSelection() { _sel = -1; }
        /// <summary>Cycles the actual animation preview list, flushing the preceding live edit.</summary>
        internal static void StepClip(int delta) { Flush(); if (_list.Count == 0) { _sel = -1; return; } _sel += delta; if (_sel >= _list.Count) _sel = -1; else if (_sel < -1) _sel = _list.Count - 1; }
        /// <summary>Copies detached current pose data for an explicit editor read.</summary>
        internal static CharacterPoseDraft Draft() { return new CharacterPoseDraft { Weapon=CurrentWeapon, Clip=CurrentPose, Shown=CurrentShown==null?null:(float[])CurrentShown.Clone(), Frame=CurrentFrame, Clips=_list.ToArray(), Selected=_sel, UserCount=_user.Count, BuiltinCount=_builtin.Count, AimCount=AimLift.UserCount, FilePath=_file, Editing=Editing, ThirdPerson=ThirdPerson.On, CanEditArms=AimLift.CanEditArms, AimWeapon=AimLift.EditWeapon, AimClip=AimLift.EditClip, AimFrame=AimLift.EditFrame, Crouched=AimLift.EditCrouched, Aim=(float[])AimLift.Get(AimLift.EditWeapon,AimLift.EditClip,AimLift.EditCrouched).Clone(), Status=_status, Note=_note, AimLine=AimLine }; }
        /// <summary>Publishes the actual drawn pose before asking the current Tools owner for motion.</summary>
        public static bool Keys(string weapon,string pose,float[] shown,out Vector3 move,out Vector3 rot) { move=rot=Vector3.zero; if(Editing && !string.IsNullOrEmpty(weapon)){ CurrentWeapon=weapon;CurrentPose=pose??"";CurrentShown=shown;CurrentFrame=Time.frameCount; } if(!Editing || string.IsNullOrEmpty(weapon) || Time.timeScale<.01f || ApocasetterBridge.InputBlocked || !Application.isFocused){ Flush();AimLift.EndArmKeys();return false; } var value=PoseEditorApi.WeaponInput(); move=value.Move;rot=value.Rotation;return value.Apply; }
        /// <summary>Finishes arm edits when the playable character is no longer eligible.</summary>
        public static void ClearHint(){if(!Editing || !ThirdPerson.On || Game.InCar || Game.Dead || string.IsNullOrEmpty(Game.DrawnWeapon))AimLift.EndArmKeys();}
        /// <summary>Exports the complete authored pose table as source.</summary>
        private static void ExportBuiltinTable()
        {
            // the complete table (built in + yours) as C#, ready to replace BuiltinPoses.cs
            var all = new Dictionary<string, float[]>(_builtin);
            foreach (var kv in _user) all[kv.Key] = kv.Value;
            var ak = new List<string>(all.Keys); ak.Sort(Compare);
            var cs = new StringBuilder();
            cs.AppendLine("namespace WildWasteland.Modules.PlayerBody");
            cs.AppendLine("{");
            cs.AppendLine("    // Weapon poses hard-coded in the mod (generated by Wild Wasteland from config/WildWasteland/PlayerBody/weapon-poses.txt on " + DateTime.Now.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture) + ").");
            cs.AppendLine("    // \"weapon|Animation|x, y, z (cm), rotation x, y, z (degrees)\" of the weapon model in her right hand. weapon-poses.txt overrides these.");
            cs.AppendLine("    internal static class BuiltinPoses");
            cs.AppendLine("    {");
            cs.AppendLine("        public static readonly string[] Data =");
            cs.AppendLine("        {");
            foreach (var k in ak) cs.Append("            \"").Append(k).Append('|').Append(Fmt(all[k])).AppendLine("\",");
            cs.AppendLine("        };");
            cs.AppendLine("    }");
            cs.AppendLine("}");
            File.WriteAllText(_export, cs.ToString());
        }
        /// <summary>Records the live presentation diagnostic.</summary>
        public static void Note(string s) { _note = s ?? ""; }
        /// <summary>Records the current presentation status.</summary>
        public static void Status(string s) { _status = s ?? ""; _statusSig = -1; }
        /// <summary>Removes the current authored weapon pose.</summary>
        internal static bool DeleteCurrent() { if (string.IsNullOrEmpty(CurrentWeapon) || string.IsNullOrEmpty(CurrentPose)) return false; Flush(); Put(CurrentWeapon, CurrentPose, null); Save(); return true; }
        /// <summary>Flushes and saves authored weapon poses.</summary>
        internal static void SaveNow() { Flush(); Save(); }
        /// <summary>Drops unsaved live weapon edits and reloads authored values.</summary>
        internal static void ReloadFiles() { _live = null; _liveKey = null; LoadUser(); }
        /// <summary>Updates cached status when animation state changes.</summary>
        private static int _statusSig = -1;
        /// <summary>Rebuilds status only when the relevant animation flags change.</summary>
        public static void Status(Props.Kind kind,bool reloading,bool firing,bool aiming){int sig=(int)kind*8+(reloading?4:0)+(firing?2:0)+(aiming?1:0);if(sig==_statusSig)return;_statusSig=sig;_status=kind.ToString()+" animations"+(reloading?", RELOADING":"")+(firing?", firing":aiming?", aiming":"");}
    }
}
